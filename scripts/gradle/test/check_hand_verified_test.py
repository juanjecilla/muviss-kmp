#!/usr/bin/env python3
# Tests scripts/gradle/check-hand-verified.py (#859): a hand-verified checksum for a version the pins
# do not list is flagged, pruned on request, and a Kotlin bump fails until the pins say otherwise.
# Run by verification-test.sh; needs no Gradle and no network.
import contextlib
import importlib.util
import io
import os
import tempfile
import unittest
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPTS = os.path.join(HERE, "..")
ROOT = os.path.join(HERE, "..", "..", "..")

_spec = importlib.util.spec_from_file_location("check_hand_verified", os.path.join(SCRIPTS, "check-hand-verified.py"))
checker = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(checker)
NS = checker.NS
HAND = "Official GitHub release asset version_130, sha256 computed locally and matched to the release digest"

METADATA = f"""<?xml version="1.0" encoding="UTF-8"?>
<verification-metadata xmlns="{NS}" version="1.3">
   <configuration>
      <verify-metadata>true</verify-metadata>
      <verify-signatures>false</verify-signatures>
   </configuration>
   <components>
      <component group="com.example" name="gradle-made" version="1.0">
         <artifact name="gradle-made-1.0.jar">
            <sha256 value="{'a' * 64}" origin="Generated by Gradle"/>
         </artifact>
      </component>
      <component group="com.github.webassembly" name="binaryen" version="129">
         <artifact name="binaryen-129-x86_64-linux.tar.gz">
            <sha256 value="{'b' * 64}" origin="{HAND}"/>
         </artifact>
      </component>
      <component group="com.github.webassembly" name="binaryen" version="130">
         <artifact name="binaryen-130-x86_64-linux.tar.gz">
            <sha256 value="{'c' * 64}" origin="{HAND}"/>
         </artifact>
      </component>
      <component group="org.nodejs" name="node" version="26.2.0">
         <artifact name="node-v26.2.0-linux-arm64.tar.gz">
            <sha256 value="{'d' * 64}" origin="Official nodejs.org tarball, sha256 computed locally and matched to the SHASUMS256.txt of the release"/>
         </artifact>
      </component>
   </components>
</verification-metadata>
"""

PINS = """# fixture
kotlin 2.4.21
com.github.webassembly:binaryen 130
org.nodejs:node 26.2.0
"""


def toml(kotlin):
    return f'[versions]\nagp = "9.2"\nkotlin = "{kotlin}"\n\n[libraries]\nx = {{ module = "a:b" }}\n'


class CheckHandVerifiedTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)

    def write(self, name, text):
        path = os.path.join(self.tmp.name, name)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        return path

    def run_check(self, metadata=METADATA, kotlin="2.4.21", pins=PINS, prune=False):
        meta = self.write("verification-metadata.xml", metadata)
        libs = self.write("libs.versions.toml", toml(kotlin))
        pin = self.write("pins.txt", pins)
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            code = checker.check(meta, libs, prune=prune, pins_path=pin)
        return code, out.getvalue(), meta

    def checksums(self, path):
        root = ET.parse(path).getroot()
        found = set()
        for component in root.find(f"{{{NS}}}components"):
            for artifact in component:
                for s in artifact:
                    found.add((component.get("name"), component.get("version"), artifact.get("name")))
        return found

    def test_a_hand_verified_checksum_for_an_unlisted_version_is_flagged(self):
        code, out, _ = self.run_check()
        self.assertEqual(1, code)
        self.assertIn("binaryen 129", out)
        self.assertNotIn("binaryen 130", out)

    def test_pinned_versions_and_generated_checksums_pass(self):
        code, out, _ = self.run_check(metadata=METADATA.replace("binaryen\" version=\"129\"", "binaryen\" version=\"130\""))
        self.assertEqual(0, code, out)

    def test_a_kotlin_bump_fails_until_the_pins_are_updated(self):
        code, out, _ = self.run_check(kotlin="2.5.0", metadata=METADATA.replace("binaryen\" version=\"129\"", "binaryen\" version=\"130\""))
        self.assertEqual(1, code)
        self.assertIn("Kotlin 2.4.21", out)
        self.assertIn("2.5.0", out)

    def test_prune_removes_only_the_unlisted_hand_verified_checksum(self):
        code, out, meta = self.run_check(prune=True)
        self.assertEqual(0, code, out)
        self.assertIn("pruned stale hand-verified checksum: com.github.webassembly:binaryen 129", out)
        self.assertEqual(
            {
                ("gradle-made", "1.0", "gradle-made-1.0.jar"),
                ("binaryen", "130", "binaryen-130-x86_64-linux.tar.gz"),
                ("node", "26.2.0", "node-v26.2.0-linux-arm64.tar.gz"),
            },
            self.checksums(meta),
        )

    def test_prune_still_reports_a_kotlin_bump(self):
        code, out, _ = self.run_check(kotlin="2.5.0", prune=True)
        self.assertEqual(1, code)
        self.assertIn("2.5.0", out)

    def test_the_repository_files_pass_the_check(self):
        # What verification-test.sh guards: the checked-in metadata has no stale hand-verified checksum.
        meta = os.path.join(ROOT, "gradle", "verification-metadata.xml")
        libs = os.path.join(ROOT, "gradle", "libs.versions.toml")
        with tempfile.TemporaryDirectory() as tmp:
            copy = os.path.join(tmp, "verification-metadata.xml")
            with open(meta, "rb") as src, open(copy, "wb") as dst:
                dst.write(src.read())
            out = io.StringIO()
            with contextlib.redirect_stdout(out):
                code = checker.check(copy, libs, prune=False)
        self.assertEqual(0, code, out.getvalue())


if __name__ == "__main__":
    unittest.main()
