#!/usr/bin/env python3
# Tests scripts/gradle/strip-generated-checksums.py, the step behind update-verification.sh --prune (#850).
# Run by verification-test.sh; needs no Gradle and no network.
import os
import subprocess
import sys
import tempfile
import unittest
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPT = os.path.join(HERE, "..", "strip-generated-checksums.py")
NS = "https://schema.gradle.org/dependency-verification"

FIXTURE = f"""<?xml version="1.0" encoding="UTF-8"?>
<verification-metadata xmlns="{NS}" version="1.3">
   <configuration>
      <verify-metadata>true</verify-metadata>
      <verify-signatures>false</verify-signatures>
   </configuration>
   <components>
      <component group="com.example" name="gradle-made" version="1.0">
         <artifact name="gradle-made-1.0.jar">
            <sha256 value="{'a' * 64}" origin="Generated by Gradle"/>
         </artifact>
      </component>
      <component group="com.github.webassembly" name="binaryen" version="130">
         <artifact name="binaryen-130-arm64-macos.tar.gz">
            <sha256 value="{'b' * 64}" origin="Generated by Gradle"/>
         </artifact>
         <artifact name="binaryen-130-x86_64-macos.tar.gz">
            <sha256 value="{'c' * 64}" origin="Official GitHub release asset version_130, sha256 computed locally and matched to the release digest"/>
         </artifact>
      </component>
      <component group="com.example" name="mixed" version="2.0">
         <artifact name="mixed-2.0.jar">
            <sha256 value="{'d' * 64}" origin="Generated by Gradle"/>
            <sha256 value="{'e' * 64}" origin="Hand-verified"/>
         </artifact>
      </component>
   </components>
</verification-metadata>
"""


def entries(xml_text):
    root = ET.fromstring(xml_text)
    out = {}
    for comp in root.find(f"{{{NS}}}components"):
        key = (comp.get("group"), comp.get("name"), comp.get("version"))
        for art in comp:
            for s in art:
                out[(key, art.get("name"), s.get("value"))] = s.get("origin")
    return out


class StripGeneratedChecksumsTest(unittest.TestCase):
    def run_script(self, text):
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "verification-metadata.xml")
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            subprocess.run([sys.executable, "-I", SCRIPT, path], check=True)
            with open(path, encoding="utf-8") as f:
                return f.read()

    def test_keeps_hand_verified_checksums_and_drops_generated_ones(self):
        out = entries(self.run_script(FIXTURE))
        self.assertEqual(
            {
                (("com.github.webassembly", "binaryen", "130"), "binaryen-130-x86_64-macos.tar.gz", "c" * 64):
                    "Official GitHub release asset version_130, sha256 computed locally and matched to the release digest",
                (("com.example", "mixed", "2.0"), "mixed-2.0.jar", "e" * 64): "Hand-verified",
            },
            out,
        )

    def test_removes_components_and_artifacts_left_empty(self):
        text = self.run_script(FIXTURE)
        self.assertNotIn('name="gradle-made"', text)
        self.assertNotIn('name="binaryen-130-arm64-macos.tar.gz"', text)

    def test_leaves_the_verification_policy_alone(self):
        text = self.run_script(FIXTURE)
        root = ET.fromstring(text)
        config = root.find(f"{{{NS}}}configuration")
        self.assertEqual(
            ["verify-metadata", "verify-signatures"],
            [c.tag.split("}")[1] for c in config],
        )
        self.assertEqual("true", config.find(f"{{{NS}}}verify-metadata").text)
        self.assertEqual("false", config.find(f"{{{NS}}}verify-signatures").text)


if __name__ == "__main__":
    unittest.main()
